import io
from datetime import datetime
from typing import Dict, Any

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

def generate_analysis_pdf(analysis_dict: Dict[str, Any]) -> io.BytesIO:
    """Generates a professional DarkPulse AI Executive Security PDF report in memory."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    story = []
    styles = getSampleStyleSheet()

    # DarkPulse Brand Colors
    PRIMARY_RED = colors.HexColor("#FF2D55")
    DARK_BG = colors.HexColor("#0A0A0F")
    CARD_BG = colors.HexColor("#13131A")
    TEXT_WHITE = colors.HexColor("#FFFFFF")
    TEXT_MUTED = colors.HexColor("#71717A")

    # Custom Paragraph Styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=22,
        textColor=PRIMARY_RED,
        spaceAfter=4
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=10,
        textColor=TEXT_MUTED,
        spaceAfter=15
    )

    body_style = ParagraphStyle(
        'BodyDark',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        textColor=colors.HexColor("#1E1E2A"),
        leading=13
    )

    # 1. Header Banner
    story.append(Paragraph("DARKPULSE AI", title_style))
    story.append(Paragraph("EXECUTIVE SECURITY ANALYSIS REPORT • CONFIDENTIAL", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=2, color=PRIMARY_RED, spaceAfter=15))

    # 2. Metadata Table
    agent_id = analysis_dict.get("agent_id", "UNKNOWN").upper()
    mode = analysis_dict.get("mode", "CONCEPT")
    created_at = analysis_dict.get("created_at", datetime.utcnow().isoformat())
    content_summary = analysis_dict.get("content_summary", "N/A")

    meta_data = [
        [Paragraph("<b>Agent Executed:</b>", body_style), Paragraph(agent_id, body_style)],
        [Paragraph("<b>Execution Mode:</b>", body_style), Paragraph(mode, body_style)],
        [Paragraph("<b>Timestamp:</b>", body_style), Paragraph(created_at, body_style)],
        [Paragraph("<b>Target Input:</b>", body_style), Paragraph(content_summary, body_style)]
    ]

    meta_table = Table(meta_data, colWidths=[120, 420])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F4F4F5")),
        ('PADDING', (0,0), (-1,-1), 6),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#E4E4E7")),
    ]))
    
    story.append(meta_table)
    story.append(Spacer(1, 15))

    # 3. Findings Section
    story.append(Paragraph("<b>Analysis Findings & Telemetry Output</b>", ParagraphStyle('H2', fontName='Helvetica-Bold', fontSize=12, textColor=colors.black, spaceAfter=8)))
    
    result_data = analysis_dict.get("result", {})
    
    # Format JSON output cleanly into string
    import json
    formatted_json = json.dumps(result_data, indent=2)
    
    code_style = ParagraphStyle(
        'CodeStyle',
        fontName='Courier',
        fontSize=8,
        textColor=colors.HexColor("#111827"),
        leading=10
    )

    # Split long lines for PDF wrapping
    lines = formatted_json.split("\n")
    for line in lines[:60]: # Cap at 60 lines for clean 1-2 page layout
        safe_line = line.replace(" ", "&nbsp;").replace("<", "&lt;").replace(">", "&gt;")
        story.append(Paragraph(safe_line, code_style))

    story.append(Spacer(1, 20))
    story.append(HRFlowable(width="100%", thickness=0.5, color=TEXT_MUTED, spaceAfter=10))
    story.append(Paragraph("Generated by DarkPulse AI Platform • Detect the Pulse of Every Threat • https://darkpulseai.com", subtitle_style))

    doc.build(story)
    buffer.seek(0)
    return buffer