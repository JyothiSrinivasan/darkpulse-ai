def get_all_agents(mode_filter: Optional[AgentMode] = None) -> List[AgentMetadata]:
    """Return all 14 agents, optionally filtered by mode."""
    agents = list(PULSE_FLEET.values())
    if mode_filter:
        agents = [a for a in agents if a.mode == mode_filter]
    return agents

def get_agent_by_id(agent_id: str) -> Optional[AgentMetadata]:
    """Fetch a single agent by ID."""
    return PULSE_FLEET.get(agent_id.lower())